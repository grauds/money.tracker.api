CREATE OR ALTER PROCEDURE GET_MONTHLY_ACCOUNT_SUMMARY (
    DEST_CODE VARCHAR(16),
    MOIS_START INTEGER,
    AN_START INTEGER,
    MOIS_END INTEGER,
    AN_END INTEGER
)
RETURNS (
    AN INTEGER,
    MOIS INTEGER,
    ACCOUNT_ID INTEGER,
    ACCOUNT_NAME VARCHAR(255),
    CODE VARCHAR(16),
    DELTA_ORIG NUMERIC(18, 2),
    DELTA_TARGET NUMERIC(18, 2),
    BALANCE_ORIG NUMERIC(18, 2),
    BALANCE_TARGET NUMERIC(18, 2),
    MONTH_TOTAL_DELTA_TARGET NUMERIC(18, 2),
    MONTH_TOTAL_BALANCE_TARGET NUMERIC(18, 2)
)
AS
DECLARE VARIABLE V_RUB_ID INTEGER;
DECLARE VARIABLE V_DEST_ID INTEGER;
DECLARE VARIABLE V_ACC_ID INTEGER;
DECLARE VARIABLE V_ACC_NAME VARCHAR(255);
DECLARE VARIABLE V_CURR_ID INTEGER;
DECLARE VARIABLE V_CURR_CODE VARCHAR(16);
DECLARE VARIABLE V_START_DATE DATE;
DECLARE VARIABLE V_END_DATE DATE;
DECLARE VARIABLE V_CUR_MONTH DATE;
DECLARE VARIABLE V_NEXT_MONTH DATE;
DECLARE VARIABLE V_TX_DATE DATE;
DECLARE VARIABLE V_DAILY_DELTA DOUBLE PRECISION;
DECLARE VARIABLE V_CONV_DAILY DOUBLE PRECISION;
DECLARE VARIABLE V_MONTH_DELTA_ORIG DOUBLE PRECISION;
DECLARE VARIABLE V_MONTH_DELTA_TARGET DOUBLE PRECISION;
DECLARE VARIABLE V_BAL_ORIG DOUBLE PRECISION;
DECLARE VARIABLE V_BAL_TARGET DOUBLE PRECISION;
DECLARE VARIABLE V_HAS_OPS SMALLINT;
BEGIN
    SELECT ID FROM MONEYTYPE WHERE CODE = 'RUB' INTO :V_RUB_ID;
    SELECT ID FROM MONEYTYPE WHERE CODE = :DEST_CODE INTO :V_DEST_ID;

    V_START_DATE = DATEADD(:MOIS_START - 1 MONTH TO DATEADD(:AN_START - 1900 YEAR TO DATE '1900-01-01'));
    V_END_DATE   = DATEADD(:MOIS_END MONTH TO DATEADD(:AN_END - 1900 YEAR TO DATE '1900-01-01'));

    V_CUR_MONTH = :V_START_DATE;

    WHILE (:V_CUR_MONTH < :V_END_DATE) DO
    BEGIN
        V_NEXT_MONTH = DATEADD(1 MONTH TO :V_CUR_MONTH);
        AN = EXTRACT(YEAR FROM :V_CUR_MONTH);
        MOIS = EXTRACT(MONTH FROM :V_CUR_MONTH);

        -- 1. Общие суммы по всем счетам за текущий месяц (в разрезе валют счетов)
        MONTH_TOTAL_DELTA_TARGET = 0;
        MONTH_TOTAL_BALANCE_TARGET = 0;

        FOR
            SELECT DISTINCT a.MONEYTYPE, mt.CODE
            FROM ACCOUNT a
            JOIN MONEYTYPE mt ON mt.ID = a.MONEYTYPE
            INTO :V_CURR_ID, :V_CURR_CODE
        DO
        BEGIN
            SELECT COALESCE(SUM(CASE WHEN op.MONEY_SIGN = 1 THEN op.AMOUNT ELSE -op.AMOUNT END), 0)
            FROM ALL_OPERATIONS_HISTORY op
            JOIN ACCOUNT a ON a.ID = op.ACCOUNT
            WHERE a.MONEYTYPE = :V_CURR_ID
              AND op.TRANSFERDATE < :V_CUR_MONTH
            INTO :V_BAL_ORIG;

            V_MONTH_DELTA_ORIG = 0;
            V_MONTH_DELTA_TARGET = 0;

            FOR
                SELECT CAST(op.TRANSFERDATE AS DATE),
                       SUM(CASE WHEN op.MONEY_SIGN = 1 THEN op.AMOUNT ELSE -op.AMOUNT END)
                FROM ALL_OPERATIONS_HISTORY op
                JOIN ACCOUNT a ON a.ID = op.ACCOUNT
                WHERE a.MONEYTYPE = :V_CURR_ID
                  AND op.TRANSFERDATE >= :V_CUR_MONTH
                  AND op.TRANSFERDATE < :V_NEXT_MONTH
                GROUP BY 1
                INTO :V_TX_DATE, :V_DAILY_DELTA
            DO
            BEGIN
                V_MONTH_DELTA_ORIG = :V_MONTH_DELTA_ORIG + COALESCE(:V_DAILY_DELTA, 0);
                EXECUTE PROCEDURE CONVERT_AMOUNT_ON_DATE(
                    :V_DAILY_DELTA, :V_CURR_ID, :V_CURR_CODE, :V_DEST_ID, :DEST_CODE, :V_RUB_ID, :V_TX_DATE
                ) RETURNING_VALUES :V_CONV_DAILY;
                V_MONTH_DELTA_TARGET = :V_MONTH_DELTA_TARGET + COALESCE(:V_CONV_DAILY, 0);
            END

            V_BAL_ORIG = :V_BAL_ORIG + :V_MONTH_DELTA_ORIG;
            EXECUTE PROCEDURE CONVERT_AMOUNT_ON_DATE(
                :V_BAL_ORIG, :V_CURR_ID, :V_CURR_CODE, :V_DEST_ID, :DEST_CODE, :V_RUB_ID, :V_NEXT_MONTH
            ) RETURNING_VALUES :V_BAL_TARGET;

            MONTH_TOTAL_DELTA_TARGET = :MONTH_TOTAL_DELTA_TARGET + COALESCE(:V_MONTH_DELTA_TARGET, 0);
            MONTH_TOTAL_BALANCE_TARGET = :MONTH_TOTAL_BALANCE_TARGET + COALESCE(:V_BAL_TARGET, 0);
        END

        MONTH_TOTAL_DELTA_TARGET = ROUND(:MONTH_TOTAL_DELTA_TARGET, 2);
        MONTH_TOTAL_BALANCE_TARGET = ROUND(:MONTH_TOTAL_BALANCE_TARGET, 2);

        -- 2. Расчёт по каждому счёту за текущий месяц
        FOR
            SELECT a.ID,
                   COALESCE(a.NAME, 'Account #' || a.ID),
                   a.MONEYTYPE,
                   mt.CODE
            FROM ACCOUNT a
            JOIN MONEYTYPE mt ON mt.ID = a.MONEYTYPE
            WHERE EXISTS (
                SELECT 1 FROM ALL_OPERATIONS_HISTORY op
                WHERE op.ACCOUNT = a.ID AND op.TRANSFERDATE < :V_NEXT_MONTH
            )
            ORDER BY 2
            INTO :V_ACC_ID, :V_ACC_NAME, :V_CURR_ID, :V_CURR_CODE
        DO
        BEGIN
            SELECT COALESCE(SUM(CASE WHEN op.MONEY_SIGN = 1 THEN op.AMOUNT ELSE -op.AMOUNT END), 0)
            FROM ALL_OPERATIONS_HISTORY op
            WHERE op.ACCOUNT = :V_ACC_ID
              AND op.TRANSFERDATE < :V_CUR_MONTH
            INTO :V_BAL_ORIG;

            V_MONTH_DELTA_ORIG = 0;
            V_MONTH_DELTA_TARGET = 0;
            V_HAS_OPS = 0;

            FOR
                SELECT CAST(op.TRANSFERDATE AS DATE),
                       SUM(CASE WHEN op.MONEY_SIGN = 1 THEN op.AMOUNT ELSE -op.AMOUNT END)
                FROM ALL_OPERATIONS_HISTORY op
                WHERE op.ACCOUNT = :V_ACC_ID
                  AND op.TRANSFERDATE >= :V_CUR_MONTH
                  AND op.TRANSFERDATE < :V_NEXT_MONTH
                GROUP BY 1
                INTO :V_TX_DATE, :V_DAILY_DELTA
            DO
            BEGIN
                V_HAS_OPS = 1;
                V_MONTH_DELTA_ORIG = :V_MONTH_DELTA_ORIG + COALESCE(:V_DAILY_DELTA, 0);
                EXECUTE PROCEDURE CONVERT_AMOUNT_ON_DATE(
                    :V_DAILY_DELTA, :V_CURR_ID, :V_CURR_CODE, :V_DEST_ID, :DEST_CODE, :V_RUB_ID, :V_TX_DATE
                ) RETURNING_VALUES :V_CONV_DAILY;
                V_MONTH_DELTA_TARGET = :V_MONTH_DELTA_TARGET + COALESCE(:V_CONV_DAILY, 0);
            END

            V_BAL_ORIG = :V_BAL_ORIG + :V_MONTH_DELTA_ORIG;

            IF (ROUND(:V_BAL_ORIG, 2) <> 0 OR :V_HAS_OPS = 1) THEN
            BEGIN
                EXECUTE PROCEDURE CONVERT_AMOUNT_ON_DATE(
                    :V_BAL_ORIG, :V_CURR_ID, :V_CURR_CODE, :V_DEST_ID, :DEST_CODE, :V_RUB_ID, :V_NEXT_MONTH
                ) RETURNING_VALUES :V_BAL_TARGET;

                ACCOUNT_ID = :V_ACC_ID;
                ACCOUNT_NAME = :V_ACC_NAME;
                CODE = :V_CURR_CODE;
                DELTA_ORIG = ROUND(:V_MONTH_DELTA_ORIG, 2);
                DELTA_TARGET = ROUND(:V_MONTH_DELTA_TARGET, 2);
                BALANCE_ORIG = ROUND(:V_BAL_ORIG, 2);
                BALANCE_TARGET = ROUND(COALESCE(:V_BAL_TARGET, 0), 2);
                SUSPEND;
            END
        END

        V_CUR_MONTH = :V_NEXT_MONTH;
    END
END^
